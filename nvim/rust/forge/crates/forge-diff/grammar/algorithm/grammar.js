module.exports = grammar({
  name: 'algorithm',
  extras: $ => [/[ \t\r]+/],
  word: $ => $.identifier,
  rules: {
    source_file: $ => seq(repeat(choice($._newline, seq($._statement, $._newline))), optional($._statement)),
    _newline: $ => '\n',
    _statement: $ => choice(
      $.section_header,
      $.if_statement,
      $.otherwise_statement,
      $.for_statement,
      $.while_statement,
      $.return_statement,
      $.continue_statement,
      $.break_statement,
      $.assignment_statement,
      $.operation_statement,
      $.comment,
    ),
    section_header: $ => 'Algorithm',
    if_statement: $ => seq('if', field('condition', $.expression), optional(':')),
    otherwise_statement: $ => seq('otherwise', optional(seq('if', field('condition', $.expression))), optional(':')),
    for_statement: $ => seq('for', 'each', field('binding', choice($.identifier, $.group)), 'in', field('collection', $.expression), optional(':')),
    while_statement: $ => seq('while', field('condition', $.expression), optional(':')),
    return_statement: $ => seq('return', optional($.expression)),
    continue_statement: $ => 'continue',
    break_statement: $ => 'break',
    assignment_statement: $ => seq(field('target', $.expression), '←', field('value', $.expression)),
    operation_statement: $ => $.expression,
    expression: $ => repeat1(choice($.invocation, $.reference, $.number, $.string, $.operator, $.punctuation, $.group)),
    invocation: $ => prec(2, seq(field('function', $.reference), field('arguments', $.arguments))),
    reference: $ => prec.right(1, seq($.identifier, repeat(seq(choice('::', '.'), $.identifier)))),
    arguments: $ => seq('(', optional(seq($._argument, repeat(seq(',', $._argument)))), ')'),
    _argument: $ => choice($.named_argument, $.argument_value),
    named_argument: $ => prec(1, seq(field('name', $.identifier), '=', field('value', $.argument_value))),
    argument_value: $ => repeat1(choice($.invocation, $.reference, $.number, $.string, alias($._argument_operator, $.operator), '.', '::', $.group)),
    group: $ => choice(seq('(', optional($.expression), ')'), seq('[', optional($.expression), ']')),
    identifier: $ => /[\p{L}_][\p{L}\p{N}_']*/,
    number: $ => /[0-9]+(\.[0-9]+)?/,
    string: $ => token(choice(/"([^"\\\n]|\\.)*"/, /'([^'\\\n]|\\.)*'/)),
    operator: $ => choice('=', $._argument_operator),
    _argument_operator: $ => choice('and', 'or', 'not', 'in', '∈', '∉', '≤', '≥', '≠', '<', '>', '+', '-', '×', '÷', '*', '/', '%', '∪', '∩'),
    punctuation: $ => choice('.', ',', '::'),
    comment: $ => token(seq('#', /[^\n]*/)),
  },
});
