module.exports = grammar({
  name: 'algorithm',
  extras: $ => [/[ \t\r]+/],
  word: $ => $.identifier,
  rules: {
    source_file: $ => seq(repeat(choice($._newline, seq($._line, $._newline))), optional($._line)),
    _line: $ => choice($.comment, seq($._statement, optional($.comment))),
    _newline: $ => '\n',
    _statement: $ => choice(
      $.section_header,
      $.if_statement,
      $.otherwise_statement,
      $.for_statement,
      $.while_statement,
      $.return_statement,
      $.continue_statement,
      $.break_statement,
      $.assignment_statement,
      $.operation_statement,
    ),
    section_header: $ => 'Algorithm',
    if_statement: $ => seq('if', field('condition', $.expression), optional(':')),
    otherwise_statement: $ => seq('otherwise', optional(seq('if', field('condition', $.expression))), optional(':')),
    for_statement: $ => seq('for', 'each', field('binding', choice($.identifier, $.binding_group)), 'in', field('collection', $.expression), optional(':')),
    while_statement: $ => seq('while', field('condition', $.expression), optional(':')),
    return_statement: $ => seq('return', optional($.expression)),
    continue_statement: $ => 'continue',
    break_statement: $ => 'break',
    assignment_statement: $ => seq(field('target', choice($.reference, $.subscript)), '←', field('value', $.expression)),
    operation_statement: $ => $.invocation,
    expression: $ => choice($.invocation, $.reference, $.number, $.string, $.builtin, $.group, $.subscript, $.unary_expression, $.binary_expression),
    invocation: $ => prec(2, seq(field('function', $.reference), field('arguments', $.arguments))),
    reference: $ => prec.right(1, seq($.identifier, repeat(seq(choice('::', '.'), $.identifier)))),
    arguments: $ => seq('(', optional(seq($._argument, repeat(seq(',', $._argument)))), ')'),
    _argument: $ => choice($.named_argument, $.argument_value),
    named_argument: $ => prec(1, seq(field('name', $.identifier), '=', field('value', $.argument_value))),
    argument_value: $ => $.expression,
    group: $ => choice(
      seq('(', $.expression, repeat(seq(',', $.expression)), ')'),
      seq('[', optional(seq($.expression, repeat(seq(',', $.expression)))), ']'),
    ),
    binding_group: $ => seq('(', $.identifier, repeat1(seq(',', $.identifier)), ')'),
    subscript: $ => prec(8, seq(field('collection', choice($.reference, $.invocation, $.group, $.subscript)), '[', field('index', $.expression), ']')),
    unary_expression: $ => prec(7, seq(alias(choice('not', '+', '-'), $.operator), $.expression)),
    binary_expression: $ => choice(
      ...[
        [1, ['or']],
        [2, ['and']],
        [3, ['=', '≠', '≤', '≥', '<', '>', 'in', '∈', '∉']],
        [4, ['∪', '∩']],
        [5, ['+', '-']],
        [6, ['×', '÷', '*', '/', '%']],
      ].map(([precedence, operators]) => prec.left(precedence, seq(
        field('left', $.expression),
        alias(choice(...operators), $.operator),
        field('right', $.expression),
      ))),
    ),
    identifier: $ => /[\p{L}_][\p{L}\p{N}_']*/,
    builtin: $ => choice('none', 'true', 'false', 'null'),
    number: $ => /[0-9]+(\.[0-9]+)?/,
    string: $ => token(choice(/"([^"\\\n]|\\.)*"/, /'([^'\\\n]|\\.)*'/)),
    comment: $ => token(seq('#', /[^\n]*/)),
  },
});
