-- Unit tests for `forge.views.harness.attachment` (attachment.lua).
local MiniTest = require("mini.test")
local isolation = dofile("nvim/lua/forge/tests/support/isolation.lua")
local buffer = dofile("nvim/lua/forge/tests/support/buffer.lua")
local mock_client = dofile("nvim/lua/forge/tests/support/mock_client.lua")
local keymap = dofile("nvim/lua/forge/tests/support/keymap.lua")
local notify = dofile("nvim/lua/forge/tests/support/notify.lua")
local eq = MiniTest.expect.equality

local T = MiniTest.new_set({ hooks = isolation.hooks() })

T["harness_attachments"] = function()
  local attachment = require("forge.views.harness.attachment")
  local original_stat = vim.uv.fs_stat
  vim.uv.fs_stat = function(path, callback)
    if not callback then return original_stat(path) end
    if path:match("^/plan") then callback("ENOENT: missing", nil) else callback(nil, { type = "file" }) end
  end
  local requests = mock_client.respond({
    ["session.attachment.import"] = function(spec) assert(spec.session_id == "attachments") end,
  })
  local failures = notify.capture({ min_level = vim.log.levels.ERROR, notifications = true })
  local draft_buffer = buffer.scratch()
  vim.api.nvim_set_current_buf(draft_buffer)
  vim.keymap.set("n", "d", "a")
  vim.keymap.set("n", "p", "P")
  attachment.attach(draft_buffer, "attachments")
  local function selection(number, kind)
    return { id = string.rep(kind == "PDF" and "b" or "a", 64), label = "[" .. kind .. " #" .. number .. "]",
      name = kind == "PDF" and "report.pdf" or "screen.png", media_type = kind == "PDF" and "application/pdf" or "image/png",
      start = 0, ["end"] = #("[" .. kind .. " #" .. number .. "]") }
  end
  local function replace(source)
    buffer.set(draft_buffer, source)
    attachment.restore(draft_buffer, {})
    vim.api.nvim_win_set_cursor(0, { 1, 0 })
  end
  local function settle() vim.wait(20, function() return false end, 5) end
  assert(keymap.get("d").buffer == 0,
    "attachment handling shadowed the user's insert-after mapping")
  for _, mapping in ipairs(vim.api.nvim_buf_get_keymap(draft_buffer, "n")) do
    assert(mapping.lhs ~= "d" and mapping.lhs ~= "c" and mapping.lhs ~= "x"
      and mapping.lhs ~= "p" and mapping.lhs ~= "P",
      "attachment handling installed a hardcoded edit operator")
  end
  replace("ab")
  keymap.feed("dZ<Esc>")
  assert(buffer.text(draft_buffer) == "aZb", "the user's insert-after mapping did not execute")
  vim.fn.setreg('"', "Q")
  vim.api.nvim_win_set_cursor(0, { 1, 1 })
  keymap.feed("p")
  settle()
  assert(buffer.text(draft_buffer) == "aQZb", "the user's paste direction was overridden")
  vim.keymap.del("n", "d")
  vim.keymap.del("n", "p")
  replace("")
  vim.api.nvim_paste('"C:\\shots\\my image.png"', false, -1)
  settle()
  assert(#requests == 1 and attachment.pending(draft_buffer))
  vim.api.nvim_buf_set_text(draft_buffer, 0, 0, 0, 0, { "before " })
  requests[1].callback(selection(1, "Image"))
  settle()
  eq(buffer.text(draft_buffer), "before [Image #1]")
  local draft = attachment.capture(draft_buffer)
  assert(#draft.attachments == 1 and draft.attachments[1].start == 7)
  eq(draft.attachments[1].id, string.rep("a", 64))
  assert(not draft.text:find("forge%-attachment"))

  vim.api.nvim_win_set_cursor(0, { 1, 7 })
  keymap.feed("v9ly")
  eq(vim.fn.getreg('"'), "[Image #1]")
  vim.keymap.set("n", "gP", "p", { buffer = draft_buffer })
  vim.cmd.normal({ args = { "G$gP" }, bang = false })
  settle()
  eq(buffer.text(draft_buffer), "before [Image #1][Image #1]")
  assert(#attachment.capture(draft_buffer).attachments == 2, "copy lost its separate attachment state")
  vim.api.nvim_win_set_cursor(0, { 1, 7 })
  vim.keymap.set({ "n", "x" }, "gD", "d", { buffer = draft_buffer })
  keymap.feed("v9lgD")
  assert(#attachment.capture(draft_buffer).attachments == 1, "cut retained a deleted attachment")
  vim.cmd.normal({ args = { "0P" }, bang = false })
  settle()
  eq(buffer.text(draft_buffer), "[Image #1]before [Image #1]")
  eq(#attachment.capture(draft_buffer).attachments, 2)

  local saved = attachment.capture(draft_buffer)
  replace(saved.text)
  assert(#attachment.capture(draft_buffer).attachments == 0, "plain label text fabricated an attachment")
  attachment.restore(draft_buffer, saved.attachments)
  assert(#attachment.capture(draft_buffer).attachments == 2, "explicit draft restore lost attachments")
  keymap.feed("ggyyGp")
  settle()
  assert(#attachment.capture(draft_buffer).attachments == 4, "whole-line copy lost attachment objects")
  vim.cmd("normal! u")
  assert(#attachment.capture(draft_buffer).attachments == 2, "undo lost the surviving attachment objects")
  keymap.feed("<C-r>")
  assert(#attachment.capture(draft_buffer).attachments == 4, "redo failed to restore attachment objects")
  replace("[Image #1](forge-attachment:broken) <image path=missing.png>")
  eq(#attachment.capture(draft_buffer).attachments, 0)
  assert(#requests == 1, "literal marker syntax caused an import")
  keymap.feed("ggyyGp")
  settle()
  assert(#attachment.capture(draft_buffer).attachments == 0, "plain text copy reused a previous attachment")

  replace("")
  vim.api.nvim_paste("/tmp/my\\ image.png", false, 1)
  vim.api.nvim_paste("", false, 3)
  settle()
  eq(requests[2].spec.params.path, "/tmp/my image.png")
  replace("newer draft")
  requests[2].callback(selection(2, "Image"))
  settle()
  assert(buffer.text(draft_buffer) == "newer draft" and #attachment.capture(draft_buffer).attachments == 0)

  replace("")
  vim.api.nvim_paste("C:\\missing.pdf", false, -1)
  settle()
  requests[3].callback(nil, "file not found")
  settle()
  assert(buffer.text(draft_buffer) == "C:\\missing.pdf" and failures[1].message == "file not found")
  replace("")
  vim.api.nvim_paste('"C:\\one.png" "C:\\two.pdf"', false, -1)
  settle()
  requests[4].callback(selection(4, "Image"))
  settle()
  eq(requests[5].spec.params.path, "C:\\two.pdf")
  requests[5].callback(selection(5, "PDF"))
  settle()
  assert(buffer.text(draft_buffer) == "[Image #4] [PDF #5]" and #attachment.capture(draft_buffer).attachments == 2)
  replace("")
  vim.api.nvim_paste("/plan explain this", false, -1)
  settle()
  assert(#requests == 5 and buffer.text(draft_buffer) == "/plan explain this")
  replace("")
  vim.api.nvim_paste("file:///C:/shots/my%20image.png", false, -1)
  settle()
  assert(requests[6].spec.params.path:lower():gsub("\\", "/"):find("c:/shots/my image.png", 1, true))
  requests[6].callback(selection(6, "Image"))
  settle()
  local owned = attachment.capture(draft_buffer)
  vim.api.nvim_buf_set_text(draft_buffer, 0, 0, 0, 0, { string.rep("x", 4000) })
  eq(attachment.capture(draft_buffer).attachments[1].start, 4000)
  replace(owned.text)
  eq(#attachment.capture(draft_buffer).attachments, 0)
end

return T
