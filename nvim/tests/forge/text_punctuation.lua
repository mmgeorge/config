local fixture=dofile('nvim/tests/forge/support/text_fixture.lua').open()
local ok,failure=xpcall(function()
  for _,punctuation in ipairs({'.',',',';',':','!','?'}) do
    fixture.type('<Esc>')
    fixture.exec([[vim.api.nvim_buf_set_lines(0,0,-1,false,{''});vim.api.nvim_win_set_cursor(0,{1,0})]])
    fixture.type('iThis is a sentence ')
    fixture.wait('This is a sentence ')
    fixture.type(punctuation)
    fixture.wait('This is a sentence'..punctuation)
    fixture.type('<BS>')
    fixture.wait('This is a sentence ')
    fixture.type(punctuation)
    fixture.wait('This is a sentence '..punctuation)
  end
  fixture.type('<Esc>')
  fixture.exec([[vim.api.nvim_buf_set_lines(0,0,-1,false,{'Please recieve  '});vim.api.nvim_win_set_cursor(0,{1,15})]])
  fixture.type('A!')
  fixture.wait('Please receive!')
  fixture.type('<BS>')
  fixture.wait('Please recieve  ')
  fixture.type('<Esc>')
  fixture.exec([[vim.api.nvim_buf_set_lines(0,0,-1,false,{''});vim.api.nvim_win_set_cursor(0,{1,0})]])
  fixture.type('iPlease recieve ')
  fixture.wait('Please receive ')
  fixture.type('<BS>')
  fixture.wait('Please recieve')
  fixture.type(' ')
  fixture.wait('Please recieve ')
  fixture.type('.')
  fixture.wait('Please recieve.')
  fixture.type('<BS>')
  fixture.wait('Please recieve ')
  fixture.type('.')
  fixture.wait('Please recieve .')
  fixture.type('<Esc>')
  fixture.exec([[vim.api.nvim_buf_set_lines(0,0,-1,false,{'Say "hello" '});vim.api.nvim_win_set_cursor(0,{1,11})]])
  fixture.type('A.')
  fixture.wait('Say "hello".')
  fixture.type('<BS>')
  fixture.wait('Say "hello" ')
  fixture.type('<Esc>')
  fixture.exec([[vim.api.nvim_buf_set_lines(0,0,-1,false,{'`code .` '});vim.api.nvim_win_set_cursor(0,{1,9})]])
  fixture.type('A.')
  fixture.wait('`code .` .')
  assert(fixture.exec('return #text_errors')==0)
end,debug.traceback)
fixture.close()
assert(ok,failure)
print('text punctuation: spacing, combined spelling, rejection, quotes, and protected code passed')
vim.cmd('qa!')
