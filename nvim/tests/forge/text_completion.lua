local fixture=dofile('nvim/tests/forge/support/text_fixture.lua').open()
local ok,failure=xpcall(function()
  fixture.type('iPlease rec')
  fixture.wait('Please rec')
  fixture.exec([[vim.opt.completeopt={'menu','menuone'};vim.fn.complete(8,{'recieve'})]])
  assert(vim.wait(1000,function()return fixture.exec('return vim.fn.pumvisible()')==1 end,10))
  fixture.type('<C-y>')
  fixture.wait('Please recieve')
  assert(fixture.exec('return #text_requests')==0,'completion insertion triggered correction')
  fixture.type(' ')
  fixture.wait('Please receive ')
  fixture.type('<BS>')
  fixture.wait('Please recieve')
  assert(fixture.exec('return #text_errors')==0)
end,debug.traceback)
fixture.close()
assert(ok,failure)
print('text completion: accepted candidate stays untouched until a typed delimiter, then supports rejection')
vim.cmd('qa!')
