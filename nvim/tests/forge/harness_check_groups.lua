vim.loader.enable(false)
local scene = dofile("nvim/tests/forge/support/check_groups_scene.lua").open()
local success, failure = xpcall(function()
  scene.toggle("scene:checks")
  local text = table.concat(scene.lines(), "\n")
  assert(text:find("5 passed · 2 failed · 1 blocked", 1, true), text)
  for _, category in ipairs({ "Formatting", "Lint", "Validation", "Tests", "Builds" }) do
    assert(text:find(category, 1, true), "missing category " .. category)
  end
  assert(text:find("Run 1", 1, true) and text:find("Run 2", 1, true), "repeated runs were lost")
  assert(text:find("tests::layout", 1, true), "named Rust test was lost")
  assert(not text:find('"raw"', 1, true), "runner JSON leaked into the result tree")
  assert(not text:find("assertion failed", 1, true), "collapsed details leaked diagnostics")
  scene.toggle("scene:2:result:1:tool")
  text = table.concat(scene.lines(), "\n")
  assert(text:find("assertion failed: expected a category heading", 1, true), "failure diagnostics are missing")
  assert(text:find("Unicode λ and 界 remain intact", 1, true), "Unicode diagnostics changed")
  local cursor = vim.api.nvim_win_get_cursor(scene.state.transcript_win)
  scene.toggle("scene:2:result:1:tool")
  assert(vim.api.nvim_win_get_cursor(scene.state.transcript_win)[1] == cursor[1], "collapse moved the cursor")
  scene.toggle("scene:4:tool")
  assert(table.concat(scene.lines(), "\n"):find("└  no output", 1, true), "empty output spacing changed")
  scene.toggle("scene:checks")
  text = table.concat(scene.lines(), "\n")
  assert(not text:find("Formatting", 1, true), "root collapse retained descendants")
  scene.toggle("scene:checks")
  assert(table.concat(scene.lines(), "\n"):find("Run 2", 1, true), "reopen lost repeated history")
end, debug.traceback)
scene.close()
assert(success, failure)
print("harness_check_groups: passed")
