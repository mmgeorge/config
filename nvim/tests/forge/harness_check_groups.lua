vim.loader.enable(false)
local scene = dofile("nvim/tests/forge/support/check_groups_scene.lua").open()
local success, failure = xpcall(function()
  scene.toggle("scene:checks")
  local text = table.concat(scene.lines(), "\n")
  assert(text:find("5/7 passed · 1 failed · 1 blocked · 2 attempts", 1, true), text)
  for _, category in ipairs({ "Formatting", "Lint", "Validation", "Tests", "Builds" }) do
    assert(text:find(category, 1, true), "missing category " .. category)
  end
  assert(text:find("Formatting · 1/1 passed · 2 attempts · 0.1s", 1, true), text)
  assert(text:find("Tests · 3/3 passed · 2 attempts · 0.1s", 1, true), text)
  assert(text:find("Builds · 1/1 passed · 1 attempt · 0.1s", 1, true), text)
  assert(not text:find("Run 1", 1, true) and not text:find("nvim/tests/forge/first.lua", 1, true),
    "opening Checks expanded category contents")
  for _, category in ipairs({ "format", "lint", "check", "test", "build" }) do
    scene.toggle("scene:category:" .. category)
  end
  text = table.concat(scene.lines(), "\n")
  assert(text:find("Run 1", 1, true) and text:find("Run 2", 1, true), "repeated runs were lost")
  assert(text:find("nvim/tests/forge/first.lua · 2 passed · 2.4s", 1, true), text)
  assert(text:find("nvim/tests/forge/second.lua · 1 passed · 1 failed · 0.2s", 1, true), text)
  assert(text:find("Run 1 · Failed · 0.1s", 1, true), text)
  assert(not text:find("Run 1 · Lua fixtures", 1, true), "run heading repeated its check name")
  assert(text:find("tests::layout", 1, true), "named Rust test was lost")
  assert(not text:find('"suite"', 1, true), "runner JSON leaked into the result tree")
  assert(not text:find("assertion failed", 1, true), "collapsed details leaked diagnostics")
  scene.toggle("scene:2:result:1:tool")
  text = table.concat(scene.lines(), "\n")
  assert(text:find("assertion failed: expected a category heading", 1, true), "failure diagnostics are missing")
  assert(text:find("Unicode λ and 界 remain intact", 1, true), "Unicode diagnostics changed")
  local cursor = vim.api.nvim_win_get_cursor(scene.state.transcript_win)
  scene.toggle("scene:2:result:1:tool")
  assert(vim.api.nvim_win_get_cursor(scene.state.transcript_win)[1] == cursor[1], "collapse moved the cursor")
  scene.toggle("scene:4:tool")
  assert(table.concat(scene.lines(), "\n"):find("└  no output", 1, true), "empty output spacing changed")
  scene.toggle("scene:checks")
  text = table.concat(scene.lines(), "\n")
  assert(not text:find("Formatting", 1, true), "root collapse retained descendants")
  scene.toggle("scene:checks")
  assert(table.concat(scene.lines(), "\n"):find("Run 2", 1, true), "reopen lost repeated history")
  scene.toggle("scene:2:result:1:tool")
  vim.api.nvim_buf_call(scene.state.transcript_buf, function()
    vim.fn.maparg("<CR>", "n", false, true).callback()
  end)
  assert(vim.wait(5000, function()
    return vim.api.nvim_buf_get_name(0):find("ForgeToolOutput://", 1, true)
      and table.concat(vim.api.nvim_buf_get_lines(0, 0, -1, false), "\n"):find('"suite":"scene"', 1, true)
  end, 10), "full runner output was not available")
  vim.fn.maparg("q", "n", false, true).callback()
  assert(vim.api.nvim_get_current_buf() == scene.state.transcript_buf, "closing output lost the transcript")
end, debug.traceback)
scene.close()
assert(success, failure)
print("harness_check_groups: passed")
