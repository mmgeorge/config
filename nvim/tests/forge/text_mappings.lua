local fixture=dofile('nvim/tests/forge/support/text_fixture.lua').open()
local ok,failure=xpcall(function()
  fixture.exec([[
    require('forge.text').detach(vim.api.nvim_get_current_buf())
    original_backspace=function() fallback_calls=(fallback_calls or 0)+1; return vim.api.nvim_replace_termcodes('<BS>',true,false,true) end
    vim.keymap.set('i','<BS>',original_backspace,{buffer=0,expr=true,replace_keycodes=false})
    require('forge.text').attach(vim.api.nvim_get_current_buf(),{kind='markdown'})
  ]])
  fixture.type('iPlease recieve ')
  fixture.wait('Please receive ')
  fixture.type('<BS>')
  fixture.wait('Please recieve')
  assert(fixture.exec('return fallback_calls or 0')==0)
  fixture.type('<BS>')
  fixture.wait('Please reciev')
  assert(fixture.exec('return fallback_calls')==1)
  fixture.exec([[require('forge.text').detach(vim.api.nvim_get_current_buf())]])
  assert(fixture.exec([[return vim.fn.maparg('<BS>','i',false,true).callback==original_backspace]]))
  fixture.exec([[
    require('forge.text').attach(vim.api.nvim_get_current_buf(),{kind='markdown'})
    replacement_backspace=function() return '' end
    vim.keymap.set('i','<BS>',replacement_backspace,{buffer=0,expr=true})
    require('forge.text').detach(vim.api.nvim_get_current_buf())
  ]])
  assert(fixture.exec([[return vim.fn.maparg('<BS>','i',false,true).callback==replacement_backspace]]))
  fixture.exec([[
    vim.keymap.set('i','<BS>',function() return '<BS>' end,{buffer=0,expr=true})
    require('forge.text').attach(vim.api.nvim_get_current_buf(),{kind='markdown'})
  ]])
  fixture.type('<BS>')
  fixture.wait('Please recie')
end,debug.traceback)
fixture.close()
assert(ok,failure)
print('text mappings: existing expression fallback and newer mapping ownership passed')
vim.cmd('qa!')
