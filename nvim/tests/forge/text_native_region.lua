local fixture=dofile('nvim/tests/forge/support/text_fixture.lua').open()
local ok,failure=xpcall(function()
  fixture.exec([[
    require('forge.text').detach(vim.api.nvim_get_current_buf())
    vim.bo.filetype='forge'
    vim.api.nvim_buf_set_lines(0,0,-1,false,{'Read-only header','Please','Read-only footer'})
    draft=require('forge.editable').new('text-draft')
    require('forge.editable').register(draft,'body',0)
    require('forge.editable').attach(draft,vim.api.nvim_get_current_buf(),{body={start={row=1,column=0},finish={row=1,column=6}}},
      {notice=function(message)text_errors[#text_errors+1]=message end})
    vim.api.nvim_win_set_cursor(0,{2,6})
  ]])
  fixture.type('A recieve ')
  fixture.wait('Read-only header\nPlease receive \nRead-only footer')
  fixture.type('<BS>')
  fixture.wait('Read-only header\nPlease recieve\nRead-only footer')
  fixture.exec('text_hold=true')
  fixture.type(' teh ')
  assert(vim.wait(1000,function()return fixture.exec('return #text_requests')>=2 end,10))
  local captured=fixture.exec([[return require('forge.editable').capture_draft(draft,{body=true})]])
  assert(#captured==1 and captured[1].text=='Please recieve teh ')
  fixture.exec([[local request=text_requests[#text_requests]; request.callback({decision='replace',occurrence=request.occurrence.id,
    original='teh',replacement='the',profile='fixture',profile_revision='revision'})]])
  fixture.wait('Read-only header\nPlease recieve teh \nRead-only footer')
  assert(fixture.exec('return #text_errors')==0)
end,debug.traceback)
fixture.close()
assert(ok,failure)
print('text native region: guarded correction, rejection, and capture invalidation passed')
vim.cmd('qa!')
