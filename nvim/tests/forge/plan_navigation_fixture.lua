local source = vim.fn.getcwd() .. "/nvim/tests/forge/fixtures/plan_navigation/rust"
local destination = vim.fn.tempname()
local fixture = dofile("nvim/tests/forge/support/plan_navigation_fixture.lua")
local success, failure = xpcall(function()
  assert(not vim.uv.fs_stat(source .. "/Cargo.toml"), "test fixture is discoverable as a live Cargo workspace")
  assert(not vim.uv.fs_stat(source .. "/dependency/Cargo.toml"), "test dependency is discoverable as a live Cargo package")
  fixture.copy(source, destination)
  assert(vim.uv.fs_stat(destination .. "/Cargo.toml"), "test workspace manifest was not materialized")
  assert(vim.uv.fs_stat(destination .. "/dependency/Cargo.toml"), "test dependency manifest was not materialized")
  assert(vim.uv.fs_stat(destination .. "/src/lib.rs"), "fixture source was not copied")
  assert(not vim.uv.fs_stat(destination .. "/target"), "generated build output was copied into the test")
end, debug.traceback)
vim.fn.delete(destination, "rf")
assert(success, failure)
print("plan_navigation_fixture: passed")
