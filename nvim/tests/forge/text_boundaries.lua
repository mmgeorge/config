local fixture=dofile('nvim/tests/forge/support/text_fixture.lua').open()
local ok,failure=xpcall(function()
  fixture.type('iPlease recieve,')
  fixture.wait('Please receive,')
  fixture.type('<BS>')
  fixture.wait('Please recieve')
  fixture.type('<CR>')
  fixture.wait('Please recieve\n')
  fixture.type('i ')
  fixture.wait('Please recieve\nI ')
  fixture.type('<BS>')
  fixture.wait('Please recieve\ni')
  fixture.type(' <Tab>')
  fixture.wait('Please recieve\ni \t')
  fixture.type('<Esc>')
  local requests=fixture.exec('return #text_requests')
  fixture.exec([[vim.api.nvim_buf_set_lines(0,0,-1,false,{''});vim.api.nvim_win_set_cursor(0,{1,0});vim.cmd.startinsert()]])
  fixture.exec([[vim.api.nvim_paste('pasted recieve ',true,-1)]])
  fixture.wait('pasted recieve ')
  assert(fixture.exec('return #text_requests')==requests,'paste triggered correction')
  fixture.type('<Esc>')
  fixture.exec([[vim.api.nvim_buf_set_lines(0,0,-1,false,{'Please recieve'});vim.api.nvim_win_set_cursor(0,{1,13})]])
  fixture.type('A。')
  fixture.wait('Please receive。')
  fixture.type('<BS>')
  fixture.wait('Please recieve')
end,debug.traceback)
fixture.close()
assert(ok,failure)
print('text boundaries: punctuation, newline, capitalization rejection, Tab, and paste passed')
vim.cmd('qa!')
