local fixture=dofile('nvim/tests/forge/support/text_fixture.lua').open()
local ok,failure=xpcall(function()
  fixture.exec('text_hold=true')
  fixture.type('iPlease recieve ')
  assert(vim.wait(1500,function()return fixture.exec('return #text_requests')==1 end,10))
  fixture.type('<Left>')
  fixture.exec([[local request=text_requests[1];request.callback({decision='replace',occurrence=request.occurrence.id,
    original='recieve',replacement='receive',profile='fixture',profile_revision='revision'})]])
  fixture.wait('Please recieve ')
  fixture.type('<Esc>')
  fixture.exec([[vim.api.nvim_buf_set_lines(0,0,-1,false,{''})]])
  fixture.type('iPlease teh ')
  assert(vim.wait(1500,function()return fixture.exec('return #text_requests')==2 end,10))
  fixture.exec('require("forge.text").detach(vim.api.nvim_get_current_buf())')
  fixture.exec([[local request=text_requests[2];request.callback({decision='replace',occurrence=request.occurrence.id,
    original='teh',replacement='the',profile='fixture',profile_revision='revision'})]])
  fixture.wait('Please teh ')
  fixture.type('<Esc>')
  fixture.exec([[
    vim.api.nvim_buf_set_lines(0,0,-1,false,{''})
    require('forge.text').attach(vim.api.nvim_get_current_buf())
    text_hold=false
  ]])
  local before=fixture.exec('return #text_requests')
  fixture.type('qqiPlease recieve <Esc>q')
  fixture.wait('Please recieve ')
  fixture.type('@q')
  fixture.wait('Please recievePlease recieve  ')
  assert(fixture.exec('return #text_requests')==before,'macro text triggered correction')
  fixture.type('u')
  fixture.type('<C-r>')
  assert(fixture.exec('return #text_requests')==before,'undo or redo triggered correction')
  assert(fixture.exec('return #text_errors')==0)
end,debug.traceback)
fixture.close()
assert(ok,failure)
print('text lifecycle: navigation, detach, macros, undo, and redo passed')
vim.cmd('qa!')
